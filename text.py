# ============================================================
# TEXT DRAWING
# ============================================================

def draw_character(
    display,
    character,
    x,
    y,
    color=(255, 255, 255),
    scale=1
):
    character = character.upper()

    pattern = FONT.get(character, FONT["?"])

    for row, line in enumerate(pattern):
        for col, pixel in enumerate(line):

            if pixel == "1":

                for sy in range(scale):
                    for sx in range(scale):

                        display.set_pixel(
                            x + col * scale + sx,
                            y + row * scale + sy,
                            color
                        )


def character_width(scale=1):
    return 5 * scale


def character_spacing(scale=1):
    return 1 * scale


def text_width(text, scale=1):

    if not text:
        return 0

    width = 0

    for character in text:
        width += character_width(scale)
        width += character_spacing(scale)

    return width - character_spacing(scale)


def draw_text(
    display,
    text,
    x,
    y,
    color=(255, 255, 255),
    scale=1
):

    cursor_x = x

    for character in text:

        draw_character(
            display,
            character,
            cursor_x,
            y,
            color,
            scale
        )

        cursor_x += character_width(scale)
        cursor_x += character_spacing(scale)


def draw_centered_text(
    display,
    text,
    y,
    color=(255, 255, 255),
    scale=1
):

    width = text_width(text, scale)

    x = (display.width - width) // 2

    draw_text(
        display,
        text,
        x,
        y,
        color,
        scale
    )


# ============================================================
# SCROLLING TEXT
# ============================================================

def draw_scrolling_text(
    display,
    text,
    t,
    color=(255, 255, 255),
    scale=1,
    speed=10
):

    display.clear()

    width = text_width(text, scale)

    # Total distance required for one complete loop
    total_distance = display.width + width

    # Current position
    offset = int(t * speed) % total_distance

    x = display.width - offset

    # Center vertically
    text_height = 7 * scale
    y = (display.height - text_height) // 2

    draw_text(
        display,
        text,
        x,
        y,
        color,
        scale
    )